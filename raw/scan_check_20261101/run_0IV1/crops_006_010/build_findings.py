# ---------------- checks ----------------
src = SRC.read_text(encoding="utf-8").replace("\r\n", "\n")
pages = {}
for p in sorted({x["page"] for x in F}):
    pages[p] = (RUN / f"page_{p:03d}.tex").read_text(encoding="utf-8").replace("\r\n", "\n")
ok = True
for x in F:
    fx = x["fix"]
    if fx is None:
        continue
    p = x["page"]
    if x["_outside"]:
        c_page, c_src = pages[p].count(fx["old"]), src.count(fx["old"])
        print(f"p{p} OUTSIDE: page count {c_page}, source count {c_src}: {x['where'][:60]}")
        ok &= c_page == 0 and c_src == 1
        continue
    c = pages[p].count(fx["old"])
    if c != 1:
        ok = False
        print(f"p{p} BAD count {c}: {fx['old'][:70]!r}")
    pages[p] = pages[p].replace(fx["old"], fx["new"], 1)
for x in F:
    x.pop("_outside")
OUT.write_text(json.dumps(F, ensure_ascii=False, indent=1), encoding="utf-8")
counts = {}
for x in F:
    k = "misprint" if x["kind"] == "misprint_in_print" else "convention" if x["kind"] == "convention" else "normal"
    counts.setdefault(x["page"], {"normal": 0, "convention": 0, "misprint": 0})[k] += 1
print("all fixes unique in sequence:", ok)
print("findings:", len(F), counts)
