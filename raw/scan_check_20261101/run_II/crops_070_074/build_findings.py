ok = True
texts = {}
for p in range(70, 75):
    with open(os.path.join(RUN, 'page_%03d.tex' % p), encoding='utf-8', newline='') as fh:
        texts[p] = fh.read().replace('\r\n', '\n')
for i, x in enumerate(R):
    fx = x['fix']
    if fx is None:
        continue
    c = texts[x['page']].count(fx['old'])
    if c != 1:
        ok = False
        sys.stdout.buffer.write(('BAD %d p.%d count=%d old=%r\n' % (i, x['page'], c, fx['old'])).encode('utf-8'))
    if fx['old'] == fx['new']:
        ok = False
        sys.stdout.buffer.write(('SAME %d\n' % i).encode('utf-8'))
# overlapping olds on the same page
for p in range(70, 75):
    spans = []
    for i, x in enumerate(R):
        if x['page'] == p and x['fix']:
            s = texts[p].find(x['fix']['old'])
            spans.append((s, s + len(x['fix']['old']), i))
    spans.sort()
    for a, b in zip(spans, spans[1:]):
        if b[0] < a[1]:
            ok = False
