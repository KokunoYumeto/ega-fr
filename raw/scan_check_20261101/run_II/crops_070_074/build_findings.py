def L(*parts):
    return '\n'.join(parts)


def F(page, where, scan, tex, kind, conv, conf, old, new, note, corrected=None):
    d = {'page': page, 'where': where, 'scan': scan, 'tex': tex, 'kind': kind,
         'convention': conv, 'confidence': conf,
         'fix': None if old is None else {'old': old, 'new': new}}
    if kind == 'misprint_in_print':
        d['corrected'] = corrected
    d['note'] = note
    return d


def conv2(page, where, label, chap, num):
    old = r'(\hyperref[' + label + r']{' + chap + ', ' + num + '})'
    new = r'(\hyperref[' + label + r']{\textbf{' + chap + '}, ' + num + '})'
    return F(page, where, '(' + chap + ', ' + num + ') with bold ' + chap,
             'plain ' + chap + ' in the link text', 'convention', 2, 'high', old, new, None)


